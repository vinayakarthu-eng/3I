import { context, SpanKind, SpanStatusCode, trace, type Attributes, type Context } from "@opentelemetry/api";
import { SeverityNumber } from "@opentelemetry/api-logs";
import type { SignalPlan } from "@drillforce/shared";
import type { Telemetry } from "./telemetry";

/**
 * Turns one second of a signal stream into telemetry. `units` requests/queries/log lines happen
 * this second, `failures` of them fail. Spans carry real timings (spread over the second), status,
 * HTTP/DB semantic attributes and exception events; logs are correlated to their spans.
 */

export interface StreamRef {
  signalId: string;
  drillId: string;
}

export interface Emitted {
  spans: number;
  logs: number;
  events: number;
  samples: string[];
}

/** Current values for observable gauges (pool usage, replica lag), by signal id. */
export const gauges = new Map<string, { kind: "pool" | "lag"; service: string; value: number; poolSize?: number; db?: string; signalId: string; drillId: string }>();

const rand = (min: number, max: number) => min + Math.random() * (max - min);
const jitter = (ms: number) => Math.max(1, Math.round(ms * rand(0.7, 1.3)));
const nowMs = () => Date.now();

function base(ref: StreamRef): Attributes {
  return { drill_id: ref.drillId, signal_id: ref.signalId, "drillforce.drill": true };
}

// One set of instruments per service, created lazily.
const instruments = new Map<string, ReturnType<typeof makeInstruments>>();
function makeInstruments(tel: Telemetry, service: string) {
  const meter = tel.service(service).meter;
  return {
    httpDuration: meter.createHistogram("http.server.request.duration", { unit: "s", description: "HTTP server request duration" }),
    dbDuration: meter.createHistogram("db.client.operation.duration", { unit: "s", description: "Database operation duration" }),
    requests: meter.createCounter("drillforce.requests", { description: "Requests generated by the drill" }),
    errors: meter.createCounter("drillforce.errors", { description: "Failed requests/queries generated by the drill" }),
  };
}
function inst(tel: Telemetry, service: string) {
  let i = instruments.get(service);
  if (!i) {
    i = makeInstruments(tel, service);
    instruments.set(service, i);
  }
  return i;
}

let gaugesRegistered = false;
/** Register the observable gauges once; they report whatever `gauges` holds at collection time. */
export function registerGauges(tel: Telemetry) {
  if (gaugesRegistered) return;
  gaugesRegistered = true;
  const byService = new Set<string>(["checkout-api", "postgres-replica", "postgres-primary"]);
  for (const service of byService) {
    const meter = tel.service(service).meter;
    meter
      .createObservableGauge("db.client.connection.count", { description: "Connections in the pool by state" })
      .addCallback((r) => {
        for (const g of gauges.values()) {
          if (g.kind !== "pool" || g.service !== service) continue;
          const attrs = { drill_id: g.drillId, signal_id: g.signalId, "db.client.connection.pool.name": g.db ?? "default" };
          r.observe(Math.round(g.value), { ...attrs, "db.client.connection.state": "used" });
          r.observe(Math.max(0, (g.poolSize ?? 0) - Math.round(g.value)), { ...attrs, "db.client.connection.state": "idle" });
        }
      });
    meter
      .createObservableGauge("drillforce.db.replica_lag", { unit: "s", description: "Replication lag" })
      .addCallback((r) => {
        for (const g of gauges.values()) {
          if (g.kind === "lag" && g.service === service) r.observe(Number(g.value.toFixed(1)), { drill_id: g.drillId, signal_id: g.signalId, "db.namespace": g.db ?? "db" });
        }
      });
  }
}

interface SpanSpec {
  service: string;
  name: string;
  kind: SpanKind;
  start: number;
  durationMs: number;
  attributes: Attributes;
  error?: { type: string; message: string };
}

function span(tel: Telemetry, spec: SpanSpec, parent?: Context) {
  const s = tel.service(spec.service).tracer.startSpan(spec.name, { kind: spec.kind, startTime: spec.start, attributes: spec.attributes }, parent);
  if (spec.error) {
    s.setStatus({ code: SpanStatusCode.ERROR, message: spec.error.message });
    s.recordException({ name: spec.error.type, message: spec.error.message }, spec.start + spec.durationMs);
    s.setAttribute("error.type", spec.error.type);
  }
  s.end(spec.start + spec.durationMs);
  return { span: s, ctx: trace.setSpan(parent ?? context.active(), s) };
}

function log(tel: Telemetry, service: string, severity: "ERROR" | "WARN" | "INFO", body: string, attrs: Attributes, ctx?: Context) {
  tel.service(service).logger.emit({
    severityNumber: severity === "ERROR" ? SeverityNumber.ERROR : severity === "WARN" ? SeverityNumber.WARN : SeverityNumber.INFO,
    severityText: severity,
    body,
    attributes: attrs,
    timestamp: nowMs(),
    ...(ctx ? { context: ctx } : {}),
  });
}

/** Which failing request slots get an error, spread evenly through the second. */
function failingSet(units: number, failures: number) {
  const set = new Set<number>();
  if (failures <= 0) return set;
  const step = units / Math.min(failures, units);
  for (let i = 0; i < Math.min(failures, units); i++) set.add(Math.floor(i * step));
  return set;
}

export function generateSecond(tel: Telemetry, plan: SignalPlan, ref: StreamRef, units: number, failures: number, factor: number): Emitted {
  const out: Emitted = { spans: 0, logs: 0, events: 0, samples: [] };
  const p = plan.params;
  const attrs = base(ref);
  const t0 = nowMs() - 1000;
  const failing = failingSet(units, failures);

  switch (plan.kind) {
    case "http_errors":
    case "latency_spike": {
      const route = p.endpoint ?? "POST /api/checkout";
      const [method, path] = route.includes(" ") ? route.split(" ", 2) : ["GET", route];
      const i = inst(tel, plan.service);
      for (let k = 0; k < units; k++) {
        const fail = failing.has(k);
        const slow = plan.kind === "latency_spike";
        const total = slow ? jitter(p.latencyMs ?? 2000) : fail ? jitter(900) : jitter(120);
        const start = t0 + Math.floor((k / Math.max(units, 1)) * 1000) - total;
        const status = fail ? (p.statusCode ?? 500) : 200;
        const msg = p.errorMessage ?? "upstream payments-service returned 503";
        const root = span(tel, {
          service: plan.service,
          name: route,
          kind: SpanKind.SERVER,
          start,
          durationMs: total,
          attributes: { ...attrs, "http.request.method": method, "http.route": path, "url.path": path, "http.response.status_code": status, "server.address": plan.service },
          error: fail ? { type: `HTTP ${status}`, message: msg } : undefined,
        });
        const down = span(
          tel,
          {
            service: "payments-service",
            name: "POST /v1/charges",
            kind: SpanKind.SERVER,
            start: start + 8,
            durationMs: Math.max(1, total - 20),
            attributes: { ...attrs, "http.request.method": "POST", "http.route": "/v1/charges", "http.response.status_code": fail ? 503 : 200 },
            error: fail ? { type: "PaymentGatewayTimeout", message: "no response from gateway after 30000ms" } : undefined,
          },
          root.ctx,
        );
        span(
          tel,
          {
            service: "payments-service",
            name: "postgresql.query",
            kind: SpanKind.CLIENT,
            start: start + 12,
            durationMs: jitter(slow ? Math.min(total - 30, 400) : 6),
            attributes: { ...attrs, "db.system": "postgresql", "db.namespace": "payments", "db.operation.name": "SELECT", "db.query.text": "SELECT id, status FROM charges WHERE order_id = $1", "server.address": "postgres-primary", "peer.service": "postgres-primary" },
          },
          down.ctx,
        );
        out.spans += 3;
        i.httpDuration.record(total / 1000, { ...attrs, "http.route": path, "http.request.method": method, "http.response.status_code": status });
        i.requests.add(1, { ...attrs, "http.route": path });
        if (fail) {
          i.errors.add(1, { ...attrs, "http.route": path, "http.response.status_code": status });
          const line = `${method} ${path} ${status} in ${total}ms — ${msg}`;
          log(tel, plan.service, "ERROR", line, { ...attrs, "http.route": path, "http.response.status_code": status, "error.type": `HTTP ${status}` }, root.ctx);
          out.logs++;
          if (out.samples.length < 2) out.samples.push(line);
        } else if (slow && k % 50 === 0) {
          const line = `${method} ${path} slow request: ${total}ms (p95 SLO 800ms)`;
          log(tel, plan.service, "WARN", line, { ...attrs, "http.route": path }, root.ctx);
          out.logs++;
          if (out.samples.length < 2) out.samples.push(line);
        }
      }
      break;
    }

    case "error_logs": {
      const i = inst(tel, plan.service);
      const msg = p.errorMessage ?? "error";
      for (let k = 0; k < units; k++) {
        const line = `${msg}\n    at GatewayClient.charge (gateway-client.js:214:11)\n    at PaymentsService.capture (payments.js:88:23)`;
        log(tel, plan.service, "ERROR", line, { ...attrs, "error.type": msg.split(":")[0] });
        out.logs++;
        i.errors.add(1, attrs);
      }
      if (units) out.samples.push(msg);
      break;
    }

    case "db_query_failures":
    case "db_slow_queries":
    case "db_connection_exhaustion": {
      const db = p.dbName ?? "orders";
      const app = plan.kind === "db_connection_exhaustion" ? plan.service : "checkout-api";
      const dbService = plan.kind === "db_connection_exhaustion" ? "postgres-primary" : plan.service;
      const iApp = inst(tel, app);
      for (let k = 0; k < units; k++) {
        const fail = failing.has(k);
        const queryMs =
          plan.kind === "db_slow_queries" ? jitter(p.latencyMs ?? 1000) : plan.kind === "db_connection_exhaustion" && fail ? 5000 : fail ? jitter(30) : jitter(8);
        const start = t0 + Math.floor((k / Math.max(units, 1)) * 1000) - queryMs - 20;
        const msg =
          p.errorMessage ?? (plan.kind === "db_connection_exhaustion" ? "timeout acquiring connection from pool" : "query failed");
        const root = span(tel, {
          service: app,
          name: "POST /api/orders",
          kind: SpanKind.SERVER,
          start,
          durationMs: queryMs + 20,
          attributes: { ...attrs, "http.request.method": "POST", "http.route": "/api/orders", "http.response.status_code": fail ? 500 : 200 },
          error: fail ? { type: "HTTP 500", message: msg } : undefined,
        });
        const name = plan.kind === "db_connection_exhaustion" ? "pg.pool.connect" : "postgresql.query";
        span(
          tel,
          {
            service: app,
            name,
            kind: SpanKind.CLIENT,
            start: start + 5,
            durationMs: queryMs,
            attributes: {
              ...attrs,
              "db.system": "postgresql",
              "db.namespace": db,
              "db.operation.name": plan.kind === "db_connection_exhaustion" ? "connect" : "INSERT",
              "db.query.text": plan.kind === "db_connection_exhaustion" ? "" : "INSERT INTO orders (id, customer_id, total) VALUES ($1, $2, $3)",
              "server.address": dbService,
              "peer.service": dbService,
            },
            error: fail ? { type: plan.kind === "db_connection_exhaustion" ? "PoolTimeoutError" : "PostgresError", message: msg } : undefined,
          },
          root.ctx,
        );
        out.spans += 2;
        iApp.dbDuration.record(queryMs / 1000, { ...attrs, "db.system": "postgresql", "db.namespace": db, "server.address": dbService });
        iApp.requests.add(1, attrs);
        if (fail) {
          iApp.errors.add(1, { ...attrs, "db.namespace": db });
          const line = `ERROR ${name} on ${dbService}/${db} after ${queryMs}ms: ${msg}`;
          log(tel, app, "ERROR", line, { ...attrs, "db.system": "postgresql", "db.namespace": db, "error.type": "PostgresError" }, root.ctx);
          out.logs++;
          if (out.samples.length < 2) out.samples.push(line);
        }
      }
      if (plan.kind === "db_connection_exhaustion") {
        const pool = p.poolSize ?? 100;
        gauges.set(ref.signalId, { kind: "pool", service: plan.service, value: Math.min(pool, pool * (0.55 + 0.45 * factor)), poolSize: pool, db, ...ref });
      }
      break;
    }

    case "replica_lag": {
      const lag = (p.lagSeconds ?? 10) * factor;
      gauges.set(ref.signalId, { kind: "lag", service: plan.service, value: lag, db: p.dbName, ...ref });
      // One WARN per minute of lag samples.
      if (units > 0 && Math.floor(nowMs() / 1000) % 60 === 0) {
        const line = `WARN replication lag on ${plan.service} is ${lag.toFixed(1)}s (threshold 5s)`;
        log(tel, plan.service, "WARN", line, { ...attrs, "db.namespace": p.dbName ?? "db" });
        out.logs++;
        out.samples.push(line);
      }
      break;
    }

    case "alert_event":
      // Sent by the worker via the Datadog Events API (once per stream).
      break;
  }
  return out;
}

/** Datadog monitor-style event. Returns null on success, an error message otherwise. */
export async function sendDatadogEvent(plan: SignalPlan, ref: StreamRef & { drillName: string }): Promise<string | null> {
  const site = process.env.DD_SITE || "datadoghq.com";
  try {
    const res = await fetch(`https://api.${site}/api/v1/events`, {
      method: "POST",
      cache: "no-store",
      headers: { "content-type": "application/json", "DD-API-KEY": process.env.DD_API_KEY ?? "" },
      body: JSON.stringify({
        title: plan.params.monitorName ?? `[DRILL] ${plan.service} alert`,
        text: `DRILL — ${ref.drillName}. This event was injected by DrillForce for an incident-response drill.`,
        alert_type: "error",
        priority: "normal",
        source_type_name: "drillforce",
        aggregation_key: ref.drillId,
        tags: ["env:drill", `drill_id:${ref.drillId}`, `service:${plan.service}`, `priority:${plan.params.priority ?? "P2"}`, "source:drillforce"],
      }),
      signal: AbortSignal.timeout(10_000),
    });
    return res.ok ? null : `Datadog Events API returned HTTP ${res.status}`;
  } catch (err) {
    return `Couldn't reach the Datadog Events API: ${(err as Error).message}`;
  }
}
